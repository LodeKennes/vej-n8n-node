export function presetFor(operation: Operation): object {
	const input = operation.preset ? structuredClone(presets[operation.preset]) : {};
	if (operation.value === 'readToken' || operation.value === 'deleteToken') {
		return { ...input, action: operation.value === 'readToken' ? 'read' : 'delete' };
	}
	return input;
}
